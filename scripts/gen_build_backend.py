"""Write docker/build-backend.txt from the build-backend dependency group in uv.lock.

The Dockerfile installs the project build backend from that file with ``--require-hashes``,
outside the runtime venv. uv.lock already records the group's closure with every wheel hash,
so this keeps only the wheels the base image can install: ``py3-none-any``, or for compiled
packages the manylinux x86_64 and aarch64 wheels for the base image's CPython ABI whose
manylinux glibc floor that image can load. The floor is keyed by the Debian release in the
base tag (``python:X.Y-slim-<release>@sha256:...``), not by the digest.

Usage: ``uv run python scripts/gen_build_backend.py`` writes the file; ``--check`` exits 1 and
lists the differences instead. tests/test_build_backend_lock.py runs the same check.
"""

from __future__ import annotations

import argparse
import re
import sys
import tomllib
from pathlib import Path
from typing import Any

from packaging.markers import Marker
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parent.parent
GROUP = "build-backend"
TARGET = ROOT / "docker" / "build-backend.txt"
ARCHES = ("x86_64", "aarch64")
# glibc of libc6 in each Debian release the official Python image publishes.
# https://packages.debian.org/trixie/libc6 (2.41) and
# https://packages.debian.org/bookworm/libc6 (2.36).
_DEBIAN_GLIBC: dict[str, tuple[int, int]] = {
    "trixie": (2, 41),
    "bookworm": (2, 36),
}
# PEP 600 (https://peps.python.org/pep-0600/) perennial tag manylinux_<major>_<minor>.
# Legacy aliases: manylinux1 = 2.5 (PEP 513, https://peps.python.org/pep-0513/),
# manylinux2010 = 2.12 (PEP 571, https://peps.python.org/pep-0571/),
# manylinux2014 = 2.17 (PEP 599, https://peps.python.org/pep-0599/).
# musllinux is a different libc and never qualifies.
_MANYLINUX_ALIAS: dict[str, tuple[int, int]] = {
    "manylinux1": (2, 5),
    "manylinux2010": (2, 12),
    "manylinux2014": (2, 17),
}
_FROM_PYTHON = re.compile(
    r"^FROM python:(\d+\.\d+)-slim(?:-([a-z]+))?(@sha256:[0-9a-f]{64})?\b",
    re.MULTILINE,
)
HEADER = (
    "# Build backend for the Dockerfile project install: the build-backend dependency group in",
    "# pyproject.toml and its closure from uv.lock. Generated by scripts/gen_build_backend.py;",
    "# do not edit by hand. Installed with --require-hashes --only-binary=:all: to",
    "# /tmp/build-backend, outside the venv, and on PYTHONPATH only for the project install.",
    "# Wheels only: py3-none-any, or the base image's CPython manylinux x86_64 and aarch64.",
)


def base_python(dockerfile: str) -> str:
    """Return the base image Python minor version, such as ``3.14``, from its FROM lines."""
    versions = set(re.findall(r"^FROM python:(\d+\.\d+)-slim", dockerfile, re.MULTILINE))
    if len(versions) != 1:
        raise ValueError(f"expected one python:X.Y-slim base image, found {sorted(versions)}")
    return versions.pop()


def image_glibc(dockerfile: str) -> tuple[int, int]:
    """Return the glibc of the Debian release named in the pinned base-image tag.

    The release is the ``-<release>`` suffix on ``python:X.Y-slim-<release>@sha256:...``.
    Every FROM line must name the same release from ``_DEBIAN_GLIBC``. The digest is not
    consulted.
    """
    found = list(_FROM_PYTHON.finditer(dockerfile))
    if not found or any(match.group(3) is None for match in found):
        raise ValueError("unpinned base image")
    releases: list[str] = []
    for match in found:
        release = match.group(2)
        if release is None:
            raise ValueError("base image tag has no Debian release suffix")
        releases.append(release)
    unique = sorted(set(releases))
    if len(unique) != 1:
        raise ValueError(f"mixed Debian releases in the base image: {unique}")
    release = unique[0]
    if release not in _DEBIAN_GLIBC:
        raise ValueError(f"unknown Debian release {release!r}")
    return _DEBIAN_GLIBC[release]


def _manylinux_floor(platform: str) -> tuple[int, int] | None:
    """glibc ``(major, minor)`` one manylinux platform tag requires, else None."""
    perennial = re.fullmatch(r"manylinux_(\d+)_(\d+)_.+", platform)
    if perennial:
        return (int(perennial.group(1)), int(perennial.group(2)))
    for alias, floor in _MANYLINUX_ALIAS.items():
        if platform.startswith(alias + "_"):
            return floor
    return None


def _wheel_floor(platforms: list[str], arch: str) -> tuple[int, int] | None:
    """Highest manylinux glibc named for ``arch``, or None when the wheel has none.

    Pip may install the wheel because an older alias matches, then the dynamic linker
    fails if a higher manylinux tag on the same wheel exceeds the image. musllinux never
    qualifies.
    """
    floors: list[tuple[int, int]] = []
    for platform in platforms:
        if not platform.endswith("_" + arch):
            continue
        floor = _manylinux_floor(platform)
        if floor is not None:
            floors.append(floor)
    if not floors:
        return None
    return max(floors)


def _environment(python: str, machine: str) -> dict[str, str]:
    return {
        "implementation_name": "cpython",
        "os_name": "posix",
        "platform_machine": machine,
        "platform_python_implementation": "CPython",
        "platform_system": "Linux",
        "python_full_version": f"{python}.0",
        "python_version": python,
        "sys_platform": "linux",
    }


def _applies(dependency: dict[str, Any], python: str) -> bool:
    marker = dependency.get("marker")
    if marker is None:
        return True
    return any(Marker(marker).evaluate(_environment(python, arch)) for arch in ARCHES)


def _pick(candidates: list[dict[str, Any]], dependency: dict[str, Any]) -> dict[str, Any]:
    """Return the uv.lock entry a dependency points at; forked packages also carry a version."""
    if "version" in dependency:
        candidates = [p for p in candidates if p["version"] == dependency["version"]]
    if len(candidates) != 1:
        name = dependency["name"]
        raise ValueError(f"{name}: expected one matching uv.lock entry, found {len(candidates)}")
    return candidates[0]


def _closure(lock: dict[str, Any], python: str) -> list[dict[str, Any]]:
    packages: dict[str, list[dict[str, Any]]] = {}
    for package in lock["package"]:
        packages.setdefault(canonicalize_name(package["name"]), []).append(package)
    (root,) = [
        package
        for entries in packages.values()
        for package in entries
        if package.get("source", {}).get("editable") == "."
    ]
    queue = list(root.get("dev-dependencies", {}).get(GROUP, []))
    if not queue:
        raise ValueError(f"uv.lock has no {GROUP} dependency group")
    seen: dict[str, dict[str, Any]] = {}
    while queue:
        dependency = queue.pop()
        if not _applies(dependency, python):
            continue
        name = canonicalize_name(dependency["name"])
        package = _pick(packages[name], dependency)
        for extra in dependency.get("extra", []):
            queue.extend(package.get("optional-dependencies", {}).get(extra, []))
        if name not in seen:
            seen[name] = package
            queue.extend(package.get("dependencies", []))
        elif seen[name]["version"] != package["version"]:
            versions = sorted({seen[name]["version"], package["version"]})
            raise ValueError(f"{name}: the {GROUP} closure needs more than one version {versions}")
    return [seen[name] for name in sorted(seen)]


def _digests(package: dict[str, Any], python: str, glibc: tuple[int, int]) -> list[str]:
    abi = "cp" + python.replace(".", "")
    universal: list[str] = []
    native: dict[str, list[str]] = {arch: [] for arch in ARCHES}
    for wheel in package.get("wheels", []):
        filename = wheel["url"].rsplit("/", 1)[-1].removesuffix(".whl")
        py_tag, abi_tag, platform_tag = filename.split("-")[-3:]
        digest = wheel["hash"].removeprefix("sha256:")
        if abi_tag == "none" and platform_tag == "any" and "py3" in py_tag.split("."):
            universal.append(digest)
        elif py_tag == abi and abi_tag == abi:
            platforms = platform_tag.split(".")
            for arch in ARCHES:
                floor = _wheel_floor(platforms, arch)
                if floor is not None and floor <= glibc:
                    native[arch].append(digest)
    if universal:
        return sorted(universal)
    if all(len(native[arch]) == 1 for arch in ARCHES):
        return sorted(native[arch][0] for arch in ARCHES)
    raise ValueError(f"{package['name']}: no py3-none-any wheel and no single {abi} wheel per arch")


def expected() -> dict[str, tuple[str, list[str]]]:
    """Map package name to (version, sha256 digests) for the group closure in uv.lock."""
    lock = tomllib.loads((ROOT / "uv.lock").read_text(encoding="utf-8"))
    dockerfile = (ROOT / "Dockerfile").read_text(encoding="utf-8")
    python = base_python(dockerfile)
    glibc = image_glibc(dockerfile)
    return {
        canonicalize_name(package["name"]): (
            package["version"],
            _digests(package, python, glibc),
        )
        for package in _closure(lock, python)
    }


def parse(text: str) -> dict[str, tuple[str, list[str]]]:
    """Parse a hash-pinned requirements file; any other requirement line raises ValueError."""
    pins: dict[str, tuple[str, list[str]]] = {}
    for line in re.sub(r"\\\n", " ", text).splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        match = re.fullmatch(r"([A-Za-z0-9_.-]+)==(\S+)((?:\s+--hash=sha256:[0-9a-f]{64})+)", line)
        if match is None:
            raise ValueError(f"not an exact, hash-pinned requirement: {line!r}")
        name = canonicalize_name(match.group(1))
        if name in pins:
            raise ValueError(f"{name} is pinned more than once")
        pins[name] = (match.group(2), re.findall(r"[0-9a-f]{64}", match.group(3)))
    return pins


def render(pins: dict[str, tuple[str, list[str]]]) -> str:
    """Return the requirements file text for ``pins``, sorted by name."""
    lines = list(HEADER)
    for name in sorted(pins):
        version, digests = pins[name]
        lines.append(f"{name}=={version} \\")
        hashes = [f"    --hash=sha256:{digest}" for digest in sorted(digests)]
        lines.append(" \\\n".join(hashes))
    return "\n".join(lines) + "\n"


def check() -> list[str]:
    """Return the differences between docker/build-backend.txt and uv.lock (empty if none)."""
    want = expected()
    have = parse(TARGET.read_text(encoding="utf-8"))
    problems: list[str] = []
    for name in sorted(set(want) | set(have)):
        if name not in have:
            problems.append(f"{name}: in the uv.lock {GROUP} closure, missing from the file")
        elif name not in want:
            problems.append(f"{name}: in the file, not in the uv.lock {GROUP} closure")
        elif (have[name][0], sorted(have[name][1])) != (want[name][0], sorted(want[name][1])):
            problems.append(f"{name}: file has {have[name][0]}, uv.lock has {want[name][0]}")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--check", action="store_true", help="report drift instead of writing")
    args = parser.parse_args(argv)
    if args.check:
        problems = check()
        for problem in problems:
            print(problem, file=sys.stderr)
        return 1 if problems else 0
    TARGET.write_text(render(expected()), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
